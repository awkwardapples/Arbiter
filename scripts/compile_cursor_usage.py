#!/usr/bin/env python3
"""Compile docs/cursor-usage/P*.md into docs/CURSOR_USAGE.md (deterministic; --check compares only)."""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path("docs") / "cursor-usage"
TARGET = Path("docs") / "CURSOR_USAGE.md"

_LABEL = re.compile(r"^P(\d+)(?:\.(\d+))?(?:-([A-Z]))?$")
_MODEL = re.compile(r"^- \*\*(?:Tool and model|Model used|Model):\*\*\s*(.+)$", re.MULTILINE)


def _order(label: str) -> tuple[int, int, str]:
    match = _LABEL.match(label)
    if match is None:
        return (10_000, 0, label)
    major, minor, lane = match.groups()
    return (int(major), int(minor or 0), lane or "")


def _tool_and_model(text: str) -> tuple[str, str]:
    match = _MODEL.search(text)
    if match is None:
        return ("not recorded", "not recorded")
    value = match.group(1).strip()
    if "Claude Code" in value:
        tool = "Claude Code"
    elif "Cursor" in value:
        tool = "Cursor"
    else:
        tool = "not recorded"
    model = re.sub(r"\s*\([^)]*\)", "", value).replace("Claude Code CLI, ", "")
    model = re.split(r"\.\s", model)[0].split(",")[0].strip().rstrip(".")
    return (tool, model)


def render(root: Path) -> str:
    files = sorted((root / SOURCE).glob("P*.md"), key=lambda p: _order(p.stem))
    rows = ["| Pass | Tool | Model |", "|---|---|---|"]
    bodies: list[str] = []
    for path in files:
        text = path.read_text(encoding="utf-8").strip()
        tool, model = _tool_and_model(text)
        rows.append(f"| {path.stem} | {tool} | {model} |")
        demoted = re.sub(r"^(#+) ", r"#\1 ", text, flags=re.MULTILINE)
        bodies.append(f"<!-- source: {SOURCE.as_posix()}/{path.name} -->\n\n{demoted}")
    counts: dict[str, int] = {}
    for row in rows[2:]:
        tool = row.split(" | ")[1]
        counts[tool] = counts.get(tool, 0) + 1
    tally = ", ".join(f"{tool}: {n}" for tool, n in sorted(counts.items()))
    header = [
        "# Cursor and Claude Code usage",
        "",
        "Generated by `python scripts/compile_cursor_usage.py` from `docs/cursor-usage/P*.md`.",
        "Do not edit by hand.",
        "",
        f"{len(files)} pass notes ({tally}). The tool column is what each note records; "
        '"not recorded" means the note names a model but not the tool.',
        "",
        *rows,
        "",
    ]
    return "\n".join(header) + "\n" + "\n\n---\n\n".join(bodies) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if docs/CURSOR_USAGE.md is stale")
    args = parser.parse_args(argv)
    rendered = render(ROOT)
    target = ROOT / TARGET
    if args.check:
        current = target.read_text(encoding="utf-8") if target.is_file() else ""
        if current != rendered:
            print(f"{TARGET.as_posix()} is stale; run python scripts/compile_cursor_usage.py")
            return 1
        print("cursor-usage: ok")
        return 0
    target.write_text(rendered, encoding="utf-8")
    print(f"wrote {TARGET.as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
