"""Streamlit session helpers (lane P5-A)."""

from __future__ import annotations

from typing import Protocol

import streamlit as st

from ui.client import ArbiterClient


class APIClient(Protocol):
    def health(self) -> dict: ...
    def list_vendors(self) -> list: ...
    def run(self, case, *, options=None) -> dict: ...
    def list_cases(self) -> list: ...
    def get_case(self, case_id: str) -> dict: ...
    def get_trace(self, case_id: str) -> list: ...
    def replay(self, case_id: str) -> dict: ...
    def submit_review(self, case_id: str, body, *, dry_run: bool = False) -> dict: ...
    def list_precedents(self) -> list: ...
    def audit_verify(self) -> dict: ...
    def approve_contract(self, contract_id: str, body) -> dict: ...
    def eval_latest(self) -> dict: ...


def get_client() -> APIClient:
    if "api_client" in st.session_state:
        return st.session_state["api_client"]
    client = ArbiterClient()
    st.session_state["api_client"] = client
    return client
